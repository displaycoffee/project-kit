/* Packages */
import fs from 'fs';
import path from 'path';
import * as prettier from 'prettier';
import { getIconData } from '@iconify/utils';

/* Paths */
/* Note: runs from the project root, like the npm scripts */
const listPath = path.resolve('src/_core/data/icons.json');
const outputPath = path.resolve('src/_core/data/icons.ts');

/* Icon set whose names stay unprefixed (e.g. 'x'), matching the Vite projects. Icons from other sets are keyed as 'prefix:name' (e.g. 'mdi:home') */
const defaultSet = 'lucide';

/* Build src/_core/data/icons.ts with only the icons listed in icons.json, so the full sets never reach the browser */
// icons.json is { "$description": '...', "<set prefix>": [...names] }, since JSON doesn't allow comments
// Each key is an Iconify set prefix and needs its @iconify-json/<prefix> package installed as a devDependency
const list = JSON.parse(fs.readFileSync(listPath, 'utf8'));
const prefixes = Object.keys(list)
	.filter((key) => !key.startsWith('$'))
	.sort((a, b) => (a == defaultSet ? -1 : b == defaultSet ? 1 : a.localeCompare(b)));

const entries = new Map();
const errors = [];

for (const prefix of prefixes) {
	// Load the icon set package for this prefix
	let iconSet;
	try {
		({ icons: iconSet } = await import(`@iconify-json/${prefix}`));
	} catch {
		errors.push(`@iconify-json/${prefix} isn't installed. Run npm install --save-dev @iconify-json/${prefix}.`);
		continue;
	}

	for (const name of [...new Set(list[prefix])].sort()) {
		const data = getIconData(iconSet, name);
		const key = prefix == defaultSet ? name : `${prefix}:${name}`;

		if (!data) {
			errors.push(`${name} not found in @iconify-json/${prefix}. Check the names at https://icon-sets.iconify.design/${prefix}/.`);
		} else if (entries.has(key)) {
			errors.push(`${key} is listed more than once.`);
		} else {
			entries.set(key, { body: data.body, width: data.width, height: data.height });
		}
	}
}

if (errors.length) {
	errors.forEach((error) => console.error(`❌ Error: ${error}`));
	process.exit(1);
}

const code = `/* Do not edit directly, this file was generated by alexandria icons (@displaycoffee/alexandria) from icons.json. */
/* Packages */
import type { IconifyIcon } from '@iconify/react';

/* Icons used in this project, keyed by name (${defaultSet}) or 'prefix:name' (other sets) */
export const icons = {
${[...entries].map(([key, data]) => `${JSON.stringify(key)}: ${JSON.stringify(data)},`).join('\n')}
} satisfies Record<string, IconifyIcon>;
`;

// Format with the project's Prettier config so the output matches the rest of the code
const config = await prettier.resolveConfig(outputPath);
fs.writeFileSync(outputPath, await prettier.format(code, { ...config, filepath: outputPath }));

console.log(`🚀 Successfully built src/_core/data/icons.ts with ${entries.size} icons from ${prefixes.join(', ')}.`);
